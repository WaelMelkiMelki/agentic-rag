"""Compare B0 (closed-book), B1 (plain RAG) and B4 (agent) on the dev set.

This makes live LLM calls, so run it with quota to spare.

Usage:
    uv run python -m evals.run_ablation              # human-readable table
    uv run python -m evals.run_ablation --markdown   # paste-ready rows for the README
"""
import argparse
import json

from agentic_rag.agent.closed_book import ClosedBook
from agentic_rag.agent.graph import build_agent
from agentic_rag.agent.rag import SimpleRAG
from agentic_rag.llm.router import LLMRouter
from agentic_rag.retrieval.embedder import CachedEmbedder
from agentic_rag.retrieval.store import VectorStore
from evals.judges import judge_answer


def run_ablation(markdown: bool = False):
    router = LLMRouter()
    b0 = ClosedBook(router=router)
    b1 = SimpleRAG(router=router)
    b4 = build_agent(router, CachedEmbedder(), VectorStore(), top_k=5,
                     max_router_calls=10, max_rounds=2)
    judge_llm = router.get_llm("openrouter")
    with open("evals/dataset/dev_set.jsonl", encoding="utf-8") as f:
        questions = [json.loads(line) for line in f if line.strip()]
    answerable = [q for q in questions if q["answerable"]]
    unanswerable = [q for q in questions if not q["answerable"]]
    b0_scores, b1_scores, b4_scores = [], [], []
    b0_refusals = b1_refusals = b4_refusals = b4_calls = 0

    for q in answerable:
        r0 = b0.query(q["question"])
        b0_scores.append(judge_answer(q["question"], q["gold_answer"], r0["answer"], judge_llm))
        r1 = b1.ask(q["question"])
        b1_scores.append(judge_answer(q["question"], q["gold_answer"], r1["answer"], judge_llm))
        r4 = b4.invoke({"question": q["question"], "router_calls": 0, "steps": []},
                       config={"recursion_limit": 25})
        b4_scores.append(judge_answer(q["question"], q["gold_answer"], r4["final_answer"], judge_llm))
        b4_calls += r4["router_calls"]
        print(
            f"{q['id']}: B0={b0_scores[-1]}/5 B1={b1_scores[-1]}/5 "
            f"B4={b4_scores[-1]}/5 calls={r4['router_calls']}"
        )

    for q in unanswerable:
        r0 = b0.query(q["question"])
        r1 = b1.ask(q["question"])
        r4 = b4.invoke({"question": q["question"], "router_calls": 0, "steps": []},
                       config={"recursion_limit": 25})
        b0_refusals += r0["status"] == "abstained"
        b1_refusals += "cannot answer" in r1["answer"].lower()
        b4_refusals += r4["status"] == "abstained"

    avg0 = sum(b0_scores) / len(b0_scores) if b0_scores else 0
    avg1 = sum(b1_scores) / len(b1_scores) if b1_scores else 0
    avg4 = sum(b4_scores) / len(b4_scores) if b4_scores else 0
    ref0 = b0_refusals / len(unanswerable) if unanswerable else 0
    ref1 = b1_refusals / len(unanswerable) if unanswerable else 0
    ref4 = b4_refusals / len(unanswerable) if unanswerable else 0
    calls = b4_calls / len(questions) if questions else 0
    if markdown:
        print("\n<!-- generated by evals/run_ablation.py --markdown -->")
        print("| System | Answer quality | Abstention | LLM calls / query |")
        print("|---|---|---|---|")
        print(f"| Closed-book (B0) | {avg0:.2f} / 5 | {ref0:.0%} | 1 |")
        print(f"| Plain RAG (B1) | {avg1:.2f} / 5 | {ref1:.0%} | 1 |")
        print(f"| Full Agent (B4) | {avg4:.2f} / 5 | {ref4:.0%} | {calls:.2f} |")
        return

    print("\nMetric                 B0       B1       B4")
    print(f"Avg answer score      {avg0:.2f}     {avg1:.2f}     {avg4:.2f}")
    print(f"Refusal rate          {ref0:.0%}     {ref1:.0%}     {ref4:.0%}")
    print(f"Avg B4 router calls      —        —      {calls:.2f}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--markdown",
        action="store_true",
        help="print a markdown table instead of the plain-text summary",
    )
    run_ablation(markdown=parser.parse_args().markdown)
